Future<void> ensureWorkSupplyPreviewInventory(
  WorkSupplyInventoryStore store,
) async {
  if (store.loadInventory().isNotEmpty) return;
  for (final record in _previewInventoryRecords()) {
    await store.addStock(record);
  }
}

