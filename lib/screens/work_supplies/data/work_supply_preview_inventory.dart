WorkSupplyItem _item({
  required String id,
  required String name,
  required String trade,
  required String category,
  required String system,
  required String itemType,
  required String variant,
  String unit = 'each',
  List<String> aliases = const [],
}) {
  return WorkSupplyItem(
    id: id,
    name: name,
    trade: trade,
    category: category,
    system: system,
    itemType: itemType,
    variant: variant,
    unit: unit,
    aliases: aliases,
  );
}

WorkSupplyInventoryRecord _record({
  required WorkSupplyItem item,
  required double onHand,
  required double threshold,
  required String storageArea,
  required String storageDetail,
  required double packagesPurchased,
  required double unitsPerPackage,
  required double lineSubtotal,
  required String merchant,
  required DateTime loggedAt,
  String purchaseType = 'each',
}) {
  final totalUnits = packagesPurchased * unitsPerPackage;
  return WorkSupplyInventoryRecord(
    item: item,
    onHand: onHand,
    threshold: threshold,
    lastUnitCost: totalUnits <= 0 ? 0 : (lineSubtotal * 1.0825) / totalUnits,
    storageArea: storageArea,
    storageDetail: storageDetail,
    receiptLinked: true,
    packagesPurchased: packagesPurchased,
    unitsPerPackage: unitsPerPackage,
    purchaseType: purchaseType,
    lineSubtotal: lineSubtotal,
    taxRate: 0.0825,
    markupRate: 0.25,
    loggedAt: loggedAt,
    sourceReceiptId: 'preview-${merchant.toLowerCase().replaceAll(' ', '-')}',
    sourceReceiptLineId: 'preview-${item.id.toLowerCase()}',
    sourceMerchantName: merchant,
  );
}
